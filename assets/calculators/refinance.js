function calcRefi() {
  const balance = readNumber('rf-balance', 0, 1e8), rate = clamp(document.getElementById('rf-rate').value, 0, 30);
  const years = clamp(document.getElementById('rf-years').value, 1, 40), newRate = clamp(document.getElementById('rf-newrate').value, 0, 30);
  const term = Number(document.getElementById('rf-term').value) || 30, costs = readNumber('rf-costs', 0, 1e6);
  const roll = document.getElementById('rf-roll').value === '1';
  const oldPay = balance ? fixedPayment(balance, rate, years) : 0;
  const newPrincipal = balance + (roll ? costs : 0);
  const newPay = newPrincipal ? fixedPayment(newPrincipal, newRate, term) : 0;
  const oldTotal = oldPay * years * 12, newTotal = newPay * term * 12;
  const oldInt = Math.max(0, oldTotal - balance), newInt = Math.max(0, newTotal - newPrincipal);
  const save = oldPay - newPay, net = oldTotal - (newTotal + (roll ? 0 : costs));
  setText('rf-newpay', money(newPay, 2));
  setText('rf-oldpay', money(oldPay, 2));
  setText('rf-save', save >= 0 ? money(save, 2) : '−' + money(-save, 2));
  setText('rf-oldint', money(oldInt));
  setText('rf-newint', money(newInt));
  setText('rf-net', net >= 0 ? money(net) : '−' + money(-net));
  let breakeven = '—';
  if (save > 0.005 && costs > 0) breakeven = yearsMonths(Math.ceil(costs / save));
  else if (save > 0.005) breakeven = 'Immediately';
  else if (costs > 0 || save < 0) breakeven = 'Never';
  setText('rf-breakeven', breakeven);
  let note;
  if (!balance) note = 'Enter your current loan balance to compare.';
  else if (save <= 0) note = `The new loan would cost ${money(-save, 2)} more per month, so refinancing only makes sense for other reasons, like a shorter term.`;
  else if (net < 0) note = `You'd save ${money(save, 2)} a month, but pay ${money(-net)} more over the life of the loan${term > years ? `, mainly because the new ${term}-year term adds ${term - years} year${term - years === 1 ? '' : 's'} of payments` : ''}. Try a shorter term.`;
  else note = `You'd save ${money(save, 2)} a month and ${money(net)} overall${costs > 0 ? `, and earn back the ${money(costs)} in closing costs in ${yearsMonths(Math.ceil(costs / save))}` : ''}. Refinancing pays off if you stay past the break-even point.`;
  setMessage('rf-note', note);
}
bindInputs(['rf-balance', 'rf-rate', 'rf-years', 'rf-newrate', 'rf-costs'], calcRefi);
['rf-term', 'rf-roll'].forEach(id => document.getElementById(id).addEventListener('change', calcRefi));
calcRefi();
